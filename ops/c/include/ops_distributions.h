/**
 * Definition of distribution functions for population of
 * ops_dat structures with random values
 */
template <template <typename> class Distribution, typename T>
struct OPSDistribution
{
  Distribution<T> *distribution;  /**< Array of random number functions */
  int dims;  /**< Number of random number functions */
  T *limits;   /**  <Limits of the distribution function - if necessary */
};


