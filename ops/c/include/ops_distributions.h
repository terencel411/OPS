/**
 * This routine produces a random point of size(dim) within the limits of the OPSDistribution
 * object
 *
 * @param Generator              Type of random number engine of the C++ standard library
 * @param OPSDistribution        Pointer to an OPSDistribution function
 * @param gen                    Random number engine
 * @param random                 Generated random point of dimension dim
 */

template<template<typename> class Distribution, typename T, typename Generator>
void ops_generate_random_point(OPSDistribution<Distribution, T> *dist_gen,
                              Generator &gen, T* random) {

  for (int i = 0; i < dist_gen->dims; i++) {
    int a1 = 0;
    T local;
    int iter = 0;
    while (a1 == 0) {
      local = dist_gen->distribution[i](gen);
      if (local >= dist_gen->limits[2 * i] && local <= dist_gen->limits[2 * i + 1])
        a1 = 1;
      iter++;
      if (iter > 100) break;
    }
    random[i] =  local;
  }
}


template<template<typename> class Distribution, typename T>
OPSDistribution<Distribution, T>* ops_free_distribution(OPSDistribution<Distribution, T>*  distri) {
  if (distri == NULL)
    return NULL;

  free(distri->limits);
  free(distri->distribution);

  free(distri);

  return NULL;
}

